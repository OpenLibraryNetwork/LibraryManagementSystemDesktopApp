package net.gizmolab.library.librarymanagementsystemdesktop.service.utilities;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ArrayNode;
import com.fasterxml.jackson.databind.node.ObjectNode;
import net.gizmolab.library.librarymanagementsystemdesktop.dto.*;
import org.junit.jupiter.api.Test;

import java.io.IOException;
import java.io.InputStream;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Tests the converter against real Strapi responses.
 * Fixtures are generated by library-strapi/tests/integration/contract-fixtures.test.js.
 */
class DTOConverterContractTest {

    private static JsonNode fixture(String name) throws IOException {
        try (InputStream in = DTOConverterContractTest.class.getResourceAsStream("/strapi-fixtures/" + name)) {
            assertNotNull(in, "Missing fixture " + name + ": run library-strapi tests/integration/contract-fixtures.test.js");
            return new ObjectMapper().readTree(in);
        }
    }

    @Test
    void contributorsKeepOrderAndRoles() throws IOException {
        PublicationDTO pub = DTOConverter.publicationFromJson(fixture("book-with-contributors.json"));
        List<ContributorDTO> contributors = pub.getContributors();
        assertEquals(2, contributors.size());
        assertEquals("Νίκη Λοϊζίδη", contributors.get(0).getPerson().getDisplayName());
        assertTrue(contributors.get(0).getRole().isAuthor());
        assertEquals("Παναγιώτης Σκόνδρας (1960-)", contributors.get(1).getPerson().getDisplayName());
        assertEquals("Μεταφραστής", contributors.get(1).getRole().getName());
        assertFalse(contributors.get(1).getRole().isAuthor());
    }

    @Test
    void authorNamesContainOnlyAuthors() throws IOException {
        PublicationDTO pub = DTOConverter.publicationFromJson(fixture("book-with-contributors.json"));
        assertEquals("Νίκη Λοϊζίδη", pub.getAuthorNames());
    }

    @Test
    void biblionetBookDetails() throws IOException {
        // Explicit null library: count every copy, whatever session another test restored into AuthService.
        PublicationDTO pub = DTOConverter.publicationFromJson(fixture("book-with-contributors.json"), null);
        assertTrue(pub.isFromBiblionet());
        assertTrue(pub.isReviewed());
        assertEquals("Νεφέλη", pub.getPublisher().getDisplayName());
        assertEquals("889.3", pub.getSubjects().get(0).getSubjectDDC());
        assertEquals(2, pub.getTotalCopies());
        assertEquals(1, pub.getAvailableCopies());
    }

    @Test
    void booksPageWithLocalBrochure() throws IOException {
        StrapiPageResponse<PublicationDTO> page = DTOConverter.publicationsPageFromJson(fixture("books-page.json"));
        assertEquals(2, page.getTotal());
        PublicationDTO brochure = page.getData().get(0);
        assertEquals("Αυτοοργάνωση", brochure.getTitle());
        assertFalse(brochure.isFromBiblionet());
        assertFalse(brochure.isReviewed());
        assertEquals("Ομάδα Γειτονιάς", brochure.getAuthorNames());
    }

    @Test
    void authorsInLibrary() throws IOException {
        StrapiPageResponse<PersonDTO> page = DTOConverter.personsPageFromJson(fixture("authors-in-library.json"));
        assertEquals(List.of("Νίκη Λοϊζίδη", "Ομάδα Γειτονιάς"),
                page.getData().stream().map(PersonDTO::getDisplayName).toList());
        assertEquals(1, page.getData().get(0).getBookCount());
        assertEquals("1950–", page.getData().get(0).getLifespan());
        assertEquals(2, page.getTotal());
    }

    @Test
    void publishersInLibrary() throws IOException {
        StrapiPageResponse<PublisherDTO> page = DTOConverter.publishersPageFromJson(fixture("publishers-in-library.json"));
        assertEquals(1, page.getData().size());
        assertEquals("Νεφέλη", page.getData().get(0).getDisplayName());
        assertEquals(1, page.getData().get(0).getBookCount());
    }

    @Test
    void contributorWithoutRoleIsIgnored() throws IOException {
        JsonNode book = fixture("book-with-contributors.json");
        ArrayNode contributors = (ArrayNode) book.path("data").path("attributes").path("contributors");
        ((ObjectNode) contributors.get(1)).putObject("role").putNull("data");
        PublicationDTO pub = DTOConverter.publicationFromJson(book);
        assertEquals(1, pub.getContributors().size());
        assertEquals("Νίκη Λοϊζίδη", pub.getAuthorNames());
    }
}
