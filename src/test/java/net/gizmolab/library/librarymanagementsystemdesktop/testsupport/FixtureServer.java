package net.gizmolab.library.librarymanagementsystemdesktop.testsupport;

import com.sun.net.httpserver.HttpServer;

import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.net.InetSocketAddress;
import java.net.URLDecoder;
import java.nio.charset.StandardCharsets;
import java.util.ArrayDeque;
import java.util.Deque;
import java.util.List;
import java.util.concurrent.CopyOnWriteArrayList;

/** Tiny HTTP server for client tests: answers by method + path prefix, records requests. */
public class FixtureServer implements AutoCloseable {

    private record Route(String method, String pathPrefix, Deque<Object[]> responses) {}

    private final HttpServer server;
    private final List<Route> routes = new CopyOnWriteArrayList<>();
    private final List<String> requests = new CopyOnWriteArrayList<>();
    private final List<String> bodies = new CopyOnWriteArrayList<>();

    public FixtureServer() throws IOException {
        server = HttpServer.create(new InetSocketAddress("127.0.0.1", 0), 0);
        server.createContext("/", exchange -> {
            String raw = exchange.getRequestURI().getRawPath()
                    + (exchange.getRequestURI().getRawQuery() != null ? "?" + exchange.getRequestURI().getRawQuery() : "");
            String path = URLDecoder.decode(raw, StandardCharsets.UTF_8);
            requests.add(exchange.getRequestMethod() + " " + path);
            bodies.add(new String(exchange.getRequestBody().readAllBytes(), StandardCharsets.UTF_8));
            Object[] response = new Object[]{404, "{\"data\":null,\"error\":{\"status\":404,\"message\":\"Not Found\"}}"};
            for (Route route : routes) {
                if (route.method().equals(exchange.getRequestMethod()) && path.startsWith(route.pathPrefix())) {
                    response = route.responses().size() > 1 ? route.responses().poll() : route.responses().peek();
                    break;
                }
            }
            byte[] bytes = ((String) response[1]).getBytes(StandardCharsets.UTF_8);
            exchange.getResponseHeaders().add("Content-Type", "application/json");
            exchange.sendResponseHeaders((Integer) response[0], bytes.length);
            exchange.getResponseBody().write(bytes);
            exchange.close();
        });
        server.start();
    }

    public FixtureServer on(String method, String pathPrefix, int status, String body) {
        return onSequence(method, pathPrefix, List.<Object[]>of(new Object[]{status, body}));
    }

    public FixtureServer onSequence(String method, String pathPrefix, List<Object[]> responses) {
        routes.add(0, new Route(method, pathPrefix, new ArrayDeque<>(responses)));
        return this;
    }

    public String url() {
        return "http://127.0.0.1:" + server.getAddress().getPort();
    }

    public List<String> requests() { return requests; }
    public List<String> bodies() { return bodies; }

    /** Contract fixture generated by library-strapi tests/integration/contract-fixtures*.test.js. */
    public static String fixture(String name) {
        try (InputStream in = FixtureServer.class.getResourceAsStream("/strapi-fixtures/" + name)) {
            if (in == null) throw new IllegalStateException("Missing fixture " + name + ": run the Strapi contract-fixtures tests");
            return new String(in.readAllBytes(), StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    @Override
    public void close() {
        server.stop(0);
    }
}
